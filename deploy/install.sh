#!/usr/bin/env bash
# ════════════════════════════════════════════════════════════════════════════
# Sentinel-SLA v2.0.0 — installer (owner-style, 5 questions).
#
#   tar xzf sentinel-sla-2.0.0.tar.gz && cd sentinel-sla-2.0.0/deploy
#   ./install.sh
#
# What it does:
#   1. checks prerequisites (bun ≥ 1.3, python3, openssl, curl)
#   2. asks the 5 questions (answers can be pre-set via env — CI-friendly:
#      SENTINEL_NONINTERACTIVE=1 SENTINEL_MODE=demo PORT=3000 ./install.sh)
#   3. generates secrets and writes .env with mode 600
#   4. installs deps, pushes the schema, builds the standalone bundle
#   5. starts the stack (demo: one process; live: web + worker), waits for
#      /api/health/ready, prints the URL and the first-run link
#
# Target install time: Demo < 5 min, Live < 15 min on a fresh VM.
# Offline-first: no downloads beyond the Bun package cache shipped with the
# release tarball is required at runtime.
# ════════════════════════════════════════════════════════════════════════════
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
# shellcheck source=lib.sh
source "$(dirname "$0")/lib.sh"
cd "$ROOT"

log()  { printf '\033[1;36m[sentinel-install]\033[0m %s\n' "$*"; }
fail() { printf '\033[1;31m[sentinel-install] FAIL:\033[0m %s\n' "$*" >&2; exit 1; }

# ── 1. prerequisites ─────────────────────────────────────────────────────────
for bin in bun python3 openssl curl; do
  command -v "$bin" >/dev/null 2>&1 || fail "$bin is required but not on PATH"
done
BUN_VER="$(bun --version)"
case "$BUN_VER" in
  0.*|1.0.*|1.1.*|1.2.*) fail "bun >= 1.3 required (found $BUN_VER). Install: https://bun.sh" ;;
esac
python3 -c 'import sqlite3' 2>/dev/null || fail "python3 lacks the sqlite3 stdlib module (backup support)"

# ── 2. the five questions ────────────────────────────────────────────────────
NONINTERACTIVE="${SENTINEL_NONINTERACTIVE:-0}"
ask() { # $1 var-name, $2 prompt, $3 default
  local __var="$1" __prompt="$2" __def="$3" __ans=""
  if [[ -n "${!__var:-}" ]]; then return; fi            # env override wins
  if [[ "$NONINTERACTIVE" == "1" ]]; then
    printf -v "$__var" '%s' "$__def"; return
  fi
  read -r -p "$__prompt [$__def]: " __ans || __ans=""
  printf -v "$__var" '%s' "${__ans:-$__def}"
}

PORT="${PORT:-3000}"
ask SENTINEL_PUBLIC_BASE_URL "1/5 Public domain or IP users will open (base URL)" "http://$(hostname -I 2>/dev/null | awk '{print $1}'):${PORT}"
ask ADMIN_EMAIL             "2/5 Admin e-mail (create the owner account with it at first run)" "admin@example.ir"
ask SENTINEL_MODE           "3/5 Mode — demo (simulation) or live (real Prometheus)" "demo"
if [[ "${SENTINEL_MODE:-demo}" == "live" ]]; then
  ask PROMETHEUS_URL       "4/5 Prometheus base URL" "http://localhost:9090"
else
  PROMETHEUS_URL="${PROMETHEUS_URL:-}"
fi
ask SENTINEL_TELEGRAM_BOT_TOKEN "5/5 Telegram bot token (optional, Enter to skip; Bale is added later in Settings → Integrations)" ""

case "${SENTINEL_MODE:-demo}" in demo|live) ;; *) fail "SENTINEL_MODE must be demo|live (got ${SENTINEL_MODE})" ;; esac
# Role: demo = one process owns HTTP + loops; live = web + dedicated worker.
SENTINEL_ROLE="all"; [[ "${SENTINEL_MODE:-demo}" == "live" ]] && SENTINEL_ROLE="web"

# ── 3. .env (mode 600, never overwritten silently) ──────────────────────────
if [[ -f .env && "${SENTINEL_ALLOW_REINSTALL:-0}" != "1" ]]; then
  fail ".env already exists at $ROOT/.env — an install seems present.
       Re-run with SENTINEL_ALLOW_REINSTALL=1 to overwrite, or run ./upgrade.sh to upgrade."
fi
log "writing .env (mode 600)"
umask 077
cat > .env <<ENV
# Sentinel-SLA v2.0.0 — generated by deploy/install.sh on $(date -u '+%Y-%m-%dT%H:%M:%SZ')
# Portable paths only; SQLite is the zero-dependency single-node default.
DATABASE_URL="file:../db/custom.db"
SENTINEL_MODE=${SENTINEL_MODE}
SENTINEL_ROLE=${SENTINEL_ROLE}
SENTINEL_DATA_DIR=$ROOT/data
PORT=$PORT
SENTINEL_PUBLIC_BASE_URL=$SENTINEL_PUBLIC_BASE_URL
SENTINEL_WEBHOOK_BEARER=$(sentinel_gen_hex 24)
SENTINEL_ACK_SECRET=$(sentinel_gen_hex 32)
SENTINEL_TELEGRAM_WEBHOOK_SECRET=$(sentinel_gen_hex 32)
SENTINEL_NOTIFY_TRANSPORT=auto
ENV
# Optional keys are OMITTED when empty — the config schema rejects
# present-but-empty secrets (e.g. bot tokens want >= 8 chars).
[[ -n "${SENTINEL_TELEGRAM_BOT_TOKEN:-}" ]] && \
  printf 'SENTINEL_TELEGRAM_BOT_TOKEN=%s\n' "$SENTINEL_TELEGRAM_BOT_TOKEN" >> .env
chmod 600 .env
# shellcheck disable=SC1091 — load our freshly written values (DATABASE_URL
# always wins over any ambient shell export — see lib.sh)
sentinel_load_env .env
export SENTINEL_MODE SENTINEL_ROLE PORT DATABASE_URL

# ── 4. dependencies, schema, build ───────────────────────────────────────────
log "installing dependencies (bun install --frozen-lockfile)"
bun install --frozen-lockfile
mkdir -p db data
log "creating the PDF report environment (.venv + WeasyPrint)"
if python3 -m venv .venv && .venv/bin/pip install --quiet -r reports/requirements.txt; then
  # The standalone server runs from .next/standalone, so point it at the venv explicitly.
  grep -q '^REPORT_PYTHON=' .env || printf 'REPORT_PYTHON=%s\n' "$ROOT/.venv/bin/python3" >> .env
  .venv/bin/python -c 'import weasyprint' 2>/dev/null \
    || log "WARNING: WeasyPrint installed but cannot load (missing Pango?). Fedora: sudo dnf install pango · Ubuntu: sudo apt install libpango-1.0-0 libpangoft2-1.0-0 — PDF reports stay disabled until fixed."
else
  log "WARNING: could not build .venv (Ubuntu: sudo apt install python3-venv). PDF reports stay disabled; everything else works."
fi
log "pushing database schema (prisma db push)"
bun x prisma db push
log "building the standalone production bundle (~1 min)"
bun run build
sentinel_sync_static "$ROOT" || fail "standalone output missing after build (did next build emit .next/standalone?)"

# Live mode: seed the Prometheus connection row (Settings → Integrations stays
# the UI of record; this is the same IntegrationSetting the wizard writes).
if [[ "${SENTINEL_MODE:-demo}" == "live" && -n "${PROMETHEUS_URL:-}" ]]; then
  log "seeding Prometheus connection ($PROMETHEUS_URL)"
  PROM_JSON="$(python3 -c 'import json,os; print(json.dumps({"baseUrl": os.environ["PROMETHEUS_URL"], "auth": {"kind": "none"}}))')"
  sentinel_prisma_eval "$ROOT" '
    const { PrismaClient } = require("@prisma/client");
    const db = new PrismaClient();
    await db.integrationSetting.upsert({
      where: { key: "prometheus" },
      update: { value: process.env.PROM_JSON, updatedAt: new Date(), updatedBy: "install.sh" },
      create: { key: "prometheus", value: process.env.PROM_JSON, updatedBy: "install.sh" },
    });
    await db.$disconnect();
  '
fi

# ── 5. start + health ────────────────────────────────────────────────────────
log "starting the stack (mode=${SENTINEL_MODE})"
sentinel_start_web "$ROOT"
if [[ "${SENTINEL_MODE:-demo}" == "live" ]]; then
  sentinel_start_worker "$ROOT"
fi
if sentinel_wait_health "$PORT" 180; then
  READY="$(sentinel_wait_health_json "$PORT" || true)"
  log "stack is healthy: $READY"
else
  fail "health check did not pass within 180 s — see $(sentinel_run_dir "$ROOT")/web.log"
fi

cat <<EOF

════════════════════════════════════════════════════════════════════
  Sentinel-SLA v2.0.0 installed — mode: ${SENTINEL_MODE}

  URL ............ ${SENTINEL_PUBLIC_BASE_URL}
  First run ...... ${SENTINEL_PUBLIC_BASE_URL}/setup
                   create the owner account with: ${ADMIN_EMAIL}

  Live mode next . Settings → Integrations: verify Prometheus, then add
                   the Telegram/Bale bot (token can also live in .env).
  Stop / logs .... kill \$(cat data/run/web.pid)  ·  data/run/web.log

  Upgrades ....... deploy/upgrade.sh   Backups: deploy/backup.sh
════════════════════════════════════════════════════════════════════
EOF
