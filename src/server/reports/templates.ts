function esc(s: string | null | undefined): string {
  return String(s ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

/** Money in Tomans, locale digits, never compact inside tables. */
function money(value: number, lang: ReportLanguage): string {
  return formatTomansFullLocale(value, lang);
}

/** Compact money for headline tiles. */
function moneyShort(value: number, lang: ReportLanguage): string {
  return formatTomansLocale(value, lang);
}

/** Availability percent from a percent value (99.95 → "99.950%"). */
function pct(value: number | null, lang: ReportLanguage, digits = 3): string {
  if (value === null) return '—';
  return formatPercentLocale(value / 100, lang, digits);
}

function num(value: number, lang: ReportLanguage): string {
  return formatNumberLocale(value, lang);
}

function dur(sec: number | null | undefined, lang: ReportLanguage): string {
  return formatDurationLocale(sec, lang);
}

/** Localised timestamp: Jalali long date + clock for fa, Gregorian for en. */
function stamp(iso: string | null | undefined, lang: ReportLanguage): string {
  if (!iso) return '—';
  const d = new Date(iso);
  return lang === 'fa'
    ? `${formatJalaliDateLong(d, 'fa')}، ${toPersianDigits(formatClock(iso))}`
    : formatDateTime(iso);
}

/** The hash and other LTR tokens keep their own direction inside RTL text. */
function ltr(s: string): string {
  return `<bdo dir="ltr">${esc(s)}</bdo>`;
}

