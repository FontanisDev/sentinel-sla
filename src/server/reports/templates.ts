/**
 * Render the complete HTML document for one report. Same snapshot + meta in,
 * deterministic document out — the only variable is the presentation
 * language. Persisted and re-renderable for the visual regression gate.
 */
export function renderReportHTML(args: {
  kind: ReportKind;
  lang: ReportLanguage;
  snapshot: ExecutiveSnapshot | StatementSnapshot | IncidentSnapshot;
  hash: string;
  meta: ReportMetaInput;
}): string {
  const { kind, lang, snapshot, hash, meta } = args;
  const dir = lang === 'fa' ? 'rtl' : 'ltr';
  const bodyClass = lang === 'fa' ? 'rtl-body' : '';

  // Period/subject line per kind: windowed kinds show the month window; the
  // incident report pins the single incident instead of a period.
  let periodValue: string;
  let periodDetail: string | undefined;
  if (snapshot.kind === 'incident') {
    periodValue = stamp(snapshot.incident.startedAt, lang);
    periodDetail = `${esc(t('serviceCol', lang))}: ${esc(
      svcName(snapshot.service.name, snapshot.service.nameFa, lang),
    )}`;
  } else {
    const w = snapshot.window;
    periodValue = esc(lang === 'fa' ? w.labelFa : w.labelEn);
    periodDetail = `${stamp(w.start, lang)} — ${stamp(w.end, lang)}`;
  }

  const sections =
    kind === 'executive'
      ? executiveSections(snapshot as ExecutiveSnapshot, lang)
      : kind === 'statement'
        ? statementSections(snapshot as StatementSnapshot, lang)
        : incidentSections(snapshot as IncidentSnapshot, lang);

  return `<!doctype html>
<html lang="${lang}" dir="${dir}">
<head>
<meta charset="utf-8">
<title>${esc(t(kind, lang))} — ${esc(PRODUCT_NAME)}</title>
<style>${css(lang)}</style>
</head>
<body class="${bodyClass}">
${titleBlock(kind, lang, { ...meta, periodValue, periodDetail }, hash)}
${sections}
</body>
</html>`;
}
