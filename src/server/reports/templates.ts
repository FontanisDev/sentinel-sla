/** Greyscale-safe penalty trend bars with printed value labels. */
function trendSvg(snap: ExecutiveSnapshot, lang: ReportLanguage): string {
  const buckets = snap.trend;
  const W = 520;
  const H = 170;
  const pad = 8;
  const labelRoom = 26;
  const barAreaW = W - pad * 2;
  const slot = barAreaW / buckets.length;
  const barW = slot * 0.5;
  const maxVal = Math.max(1, ...buckets.map((b) => b.penaltyTomans));
  const baseY = H - 34;
  const bars = buckets
    .map((b, i) => {
      const h = Math.max(2, Math.round(((baseY - pad - labelRoom) * b.penaltyTomans) / maxVal));
      const x = pad + slot * i + (slot - barW) / 2;
      const y = baseY - h;
      const cx = pad + slot * i + slot / 2;
      const label =
        b.penaltyTomans > 0 ? moneyShort(b.penaltyTomans, lang) : lang === 'fa' ? '۰' : '0';
      const below =
        lang === 'fa'
          ? `${toPersianDigits(String(b.incidents))} اختلال · ${dur(b.downtimeSec, 'fa')}`
          : `${b.incidents} incident(s) · ${dur(b.downtimeSec, 'en')}`;
      return `
  <rect x="${x.toFixed(1)}" y="${y}" width="${barW.toFixed(1)}" height="${h}" fill="#374151" stroke="#111827" stroke-width="0.6"/>
  <text x="${cx.toFixed(1)}" y="${(y - 5).toFixed(1)}" font-size="8.5" text-anchor="middle" fill="#111827">${esc(label)}</text>
  <text x="${cx.toFixed(1)}" y="${(baseY + 12).toFixed(1)}" font-size="8" text-anchor="middle" fill="#374151">${esc(lang === 'fa' ? b.labelFa : b.labelEn)}</text>
  <text x="${cx.toFixed(1)}" y="${(baseY + 24).toFixed(1)}" font-size="7.5" text-anchor="middle" fill="#6b7280">${esc(below)}</text>
  <line x1="${pad}" y1="${baseY}" x2="${(W - pad).toFixed(1)}" y2="${baseY}" stroke="#9ca3af" stroke-width="0.8"/>`;
    })
    .join('');
  return `
<div class="svg-wrap">
<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${H}" viewBox="0 0 ${W} ${H}" role="img">
  <rect x="0" y="0" width="${W}" height="${H}" fill="#ffffff"/>${bars}
</svg>
</div>`;
}

