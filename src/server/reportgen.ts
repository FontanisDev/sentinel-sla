// Sentinel-SLA — report generation pipeline.
//
// One code path for BOTH the manual POST /api/reports and the report
// scheduler (generatedBy 'scheduled') — same data snapshot, same template,
// same WeasyPrint renderer, only the origin stamp differs.
//
// Pipeline per report:
//   1. snapshot  — src/server/reports/snapshot.ts builds the complete data
//                  for the kind (real DB rows + the pure domain functions)
//                  and a SHA-256 over its canonical form;
//   2. template  — src/server/reports/templates.ts renders the bilingual
//                  HTML (fa: RTL + Persian digits + Jalali) from the SAME
//                  snapshot (language is presentation only, hash unchanged);
//   3. render    — src/server/reports/render.ts → reports/render_weasy.py
//                  (WeasyPrint) writes the PDF;
//   4. archive   — SlaReport row with kind/language/subjectId/snapshotHash/
//                  paramsJson + the retention prune.
// The title block prints the snapshot hash, so any later tampering with the
// numbers is detectable against the archived row.

import { promises as fs } from 'fs';
import path from 'path';
import { db } from '@/lib/db';
import { getConfig } from '@/server/config';
import { HttpError } from '@/server/http';
import { getTenantById, type TenantRow } from '@/server/tenants';
import { pruneReportArchiveSoon } from '@/server/reportarchive';
import {
  getExecutiveSnapshot,
  getIncidentSnapshot,
  getStatementSnapshot,
  snapshotHash,
  type ExecutiveSnapshot,
  type IncidentSnapshot,
  type ReportKind,
  type ReportLanguage,
  type StatementSnapshot,
} from '@/server/reports/snapshot';
import { renderReportHTML, type ReportMetaInput } from '@/server/reports/templates';
import { renderHtmlToPdf, reportFileName } from '@/server/reports/render';
import type { ReportDTO } from '@/lib/types';

function toReportDTO(row: {
  id: string;
  periodStart: Date;
  periodEnd: Date;
  generatedAt: Date;
  fileName: string;
  fileSize: number;
  generatedBy: string;
  kind: string;
  language: string;
  subjectId: string | null;
  snapshotHash: string;
}): ReportDTO {
  return {
    id: row.id,
    periodStart: row.periodStart.toISOString(),
    periodEnd: row.periodEnd.toISOString(),
    generatedAt: row.generatedAt.toISOString(),
    fileName: row.fileName,
    fileSize: row.fileSize,
    generatedBy: row.generatedBy,
    kind: row.kind,
    language: row.language,
    subjectId: row.subjectId,
    snapshotHash: row.snapshotHash,
  };
}

export interface GenerateReportOptions {
  /** report template (default 'executive') */
  kind: ReportKind;
  /** output language (default 'en') — same data either way */
  language: ReportLanguage;
  /** scope: tenant for statement/executive; null = fleet-wide executive */
  tenantId?: string | null;
  /** the incident to report on (kind 'incident' only) */
  incidentId?: string | null;
  /** 'manual' (POST /api/reports) or 'scheduled' (scheduler / Run now) */
  generatedBy: 'manual' | 'scheduled';
  /** display handle printed in the title block ("generated by") */
  generatedByName?: string;
}

/**
 * Generate one report PDF and persist its SlaReport row. Throws
 * HttpError(400/404) for invalid scopes and HttpError(500/503) when the
 * renderer fails — callers map both to their own error responses.
 */
export async function generateSlaReport(opts: GenerateReportOptions): Promise<ReportDTO> {
  const kind = opts.kind ?? 'executive';
  const language = opts.language ?? 'en';

  // tenant scope validation (same rule for every kind: unknown → 404)
  let tenant: TenantRow | null = null;
  if (opts.tenantId) {
    tenant = await getTenantById(opts.tenantId);
    if (!tenant) throw new HttpError(404, `Tenant '${opts.tenantId}' not found`);
  }

  // ── snapshot ────────────────────────────────────────────────────────────
  let snapshot: ExecutiveSnapshot | StatementSnapshot | IncidentSnapshot;
  let subjectId: string | null = null;
  let periodStart: Date;
  let periodEnd: Date;

  if (kind === 'incident') {
    if (!opts.incidentId) throw new HttpError(400, 'kind=incident requires incidentId');
    const inc = await getIncidentSnapshot(opts.incidentId);
    if (!inc) throw new HttpError(404, `Incident '${opts.incidentId}' not found`);
    // tenant-scope guard: an executive scoped to client A cannot report a
    // client B incident (the owning service carries the tenant).
    if (tenant && inc.tenant && inc.tenant.id !== tenant.id) {
      throw new HttpError(403, 'Incident belongs to another tenant scope');
    }
    snapshot = inc;
    subjectId = inc.incident.id;
    periodStart = new Date(inc.incident.startedAt);
    periodEnd = inc.incident.resolvedAt ? new Date(inc.incident.resolvedAt) : new Date();
  } else if (kind === 'statement') {
    if (!opts.tenantId) {
      throw new HttpError(400, 'kind=statement requires tenantId (a per-client statement)');
    }
    const st = await getStatementSnapshot(opts.tenantId);
    if (!st) throw new HttpError(404, `Tenant '${opts.tenantId}' not found`);
    snapshot = st;
    subjectId = st.contract.tenantId;
    periodStart = new Date(st.window.start);
    periodEnd = new Date(st.window.end);
  } else {
    // executive — month-to-date window, optionally scoped to one tenant
    const ex = await getExecutiveSnapshot(tenant ? tenant.id : null);
    snapshot = ex;
    periodStart = new Date(ex.window.start);
    periodEnd = new Date(ex.window.end);
  }

  const hash = snapshotHash(snapshot);
  const now = new Date();
  const meta: ReportMetaInput = {
    generatedAt: now,
    generatedBy:
      opts.generatedByName?.trim() ||
      (opts.generatedBy === 'scheduled' ? 'report scheduler' : 'operator'),
    tenantName:
      snapshot.kind === 'incident'
        ? (snapshot.tenant?.name ?? null)
        : snapshot.kind === 'statement'
          ? snapshot.contract.tenantName
          : (snapshot.scopeTenant?.name ?? null),
    tenantNameFa:
      snapshot.kind === 'incident'
        ? (snapshot.tenant?.nameFa ?? null)
        : snapshot.kind === 'statement'
          ? snapshot.contract.tenantNameFa
          : (snapshot.scopeTenant?.nameFa ?? null),
  };

  // ── template + render ───────────────────────────────────────────────────
  const html = renderReportHTML({ kind, lang: language, snapshot, hash, meta });

  const config = getConfig();
  await fs.mkdir(config.reportsDir, { recursive: true });
  const fileName = reportFileName(kind, now);
  const outPath = path.join(config.reportsDir, fileName);
  await renderHtmlToPdf(html, outPath);

  const stat = await fs.stat(outPath);
  const row = await db.slaReport.create({
    data: {
      periodStart,
      periodEnd,
      fileName,
      filePath: outPath,
      fileSize: stat.size,
      generatedBy: opts.generatedBy,
      summaryJson: JSON.stringify(
        snapshot.kind === 'executive'
          ? { kind, language, headline: snapshot.headline }
          : snapshot.kind === 'statement'
            ? { kind, language, totals: snapshot.totals }
            : { kind, language, penaltyTomans: snapshot.incident.penaltyTomans },
      ),
      kind,
      language,
      subjectId,
      snapshotHash: hash,
      paramsJson: JSON.stringify({
        kind,
        language,
        tenantId: opts.tenantId ?? null,
        incidentId: opts.incidentId ?? null,
      }),
    },
  });

  console.log(
    `[sentinel:reports] generated ${fileName} (${stat.size} bytes, kind=${kind} lang=${language}, by ${opts.generatedBy})`,
  );
  // retention: enforce the newest-N archive policy after every report
  // (fire-and-forget — never blocks this response).
  pruneReportArchiveSoon();
  return toReportDTO(row);
}

/**
 * Regenerate a report from its stored parameters (authorized API, audit-
 * logged by the route). Creates a NEW archive row with a fresh snapshot
 * hash over the CURRENT data — history is never overwritten.
 */
export async function regenerateReport(
  reportId: string,
  generatedByName: string,
): Promise<ReportDTO> {
  const row = await db.slaReport.findUnique({ where: { id: reportId } });
  if (!row) throw new HttpError(404, 'Report not found');

  let params: { kind?: string; language?: string; tenantId?: string | null; incidentId?: string | null };
  try {
    params = JSON.parse(row.paramsJson || '{}');
  } catch {
    params = {};
  }
  const kind = (params.kind ?? row.kind) as ReportKind;
  if (!['executive', 'statement', 'incident'].includes(kind)) {
    throw new HttpError(400, `Report ${reportId} has no regenerable parameters (legacy executive report)`);
  }
  return generateSlaReport({
    kind,
    language: (params.language ?? row.language) as ReportLanguage,
    tenantId: params.tenantId ?? null,
    incidentId: params.incidentId ?? null,
    generatedBy: 'manual',
    generatedByName,
  });
}
