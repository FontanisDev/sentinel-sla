#!/usr/bin/env node
// Sentinel-SLA — generated authorization matrix over the LIVE API.
//
// What it proves:
//   1. Unauthenticated request to EVERY protected route/method → 401.
//   2. Wrong role (viewer) on every mutation route → 403; admin-only reads
//      (/api/users, /api/audit) → 403 for viewer/engineer.
//   3. Tenant A member cannot touch tenant B: scoped engineer/executive get
//      403 on every tenant-scoped read with ?tenant=<B> and on cross-tenant
//      mutations (report generation, service assignment).
//   4. Same scoped user against their OWN tenant → no 403 (access still works).
//
// The route inventory is GENERATED by walking src/app/api/**/route.ts, so a
// new route that forgets its guard fails this matrix forever.
//
// Usage:
//   MATRIX_BASE_URL=http://127.0.0.1:3000 \
//   MATRIX_OWNER_EMAIL=owner@sentinel.test \
//   MATRIX_OWNER_PASSWORD='…' node tests/integration/authz-matrix.mjs
//
// Credentials live in an UNTRACKED file (.env.test) or the environment —
// never committed (hard rule). Against a server with no configured owner the
// script exits 77 (skipped), so CI without a live server stays green.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..', '..');

// ── configuration ────────────────────────────────────────────────────────────

function loadEnvTest() {
  const file = path.join(ROOT, '.env.test');
  if (!fs.existsSync(file)) return {};
  const out = {};
  for (const line of fs.readFileSync(file, 'utf8').split('\n')) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/);
    if (m && !line.trim().startsWith('#')) out[m[1]] = m[2].replace(/^['"]|['"]$/g, '');
  }
  return out;
}

const envTest = loadEnvTest();
const BASE_URL = (process.env.MATRIX_BASE_URL ?? envTest.MATRIX_BASE_URL ?? '').replace(/\/$/, '');
const OWNER_EMAIL = process.env.MATRIX_OWNER_EMAIL ?? envTest.MATRIX_OWNER_EMAIL;
const OWNER_PASSWORD = process.env.MATRIX_OWNER_PASSWORD ?? envTest.MATRIX_OWNER_PASSWORD;

if (!BASE_URL || !OWNER_EMAIL || !OWNER_PASSWORD) {
  console.log(
    '[authz-matrix] SKIP (exit 77): set MATRIX_BASE_URL, MATRIX_OWNER_EMAIL, ' +
      "MATRIX_OWNER_PASSWORD (env or untracked .env.test) against a running server.\n" +
      'This check needs a live server; unit-level enforcement is covered by ' +
      'tests/unit/authz-enumeration.test.ts.',
  );
  process.exit(77);
}

// ── tiny cookie-jar fetch ────────────────────────────────────────────────────

function makeClient() {
  let cookie = null;
  return {
    get cookie() {
      return cookie;
    },
    async req(pathname, { method = 'GET', body, headers = {}, _retried429 = false } = {}) {
      const h = { ...headers };
      if (cookie) h.cookie = cookie;
      if (body !== undefined) h['content-type'] = 'application/json';
      const res = await fetch(`${BASE_URL}${pathname}`, {
        method,
        headers: h,
        body: body === undefined ? undefined : JSON.stringify(body),
        redirect: 'manual',
      });
      // Honour the rate limiter: wait out Retry-After and retry once
      // so dense matrix sweeps are not failed by 429s. The login rule allows
      // 10 attempts / 5 min — a couple of back-to-back matrix runs legitimately
      // trip it, and the correct behaviour is to WAIT, not to weaken the rule.
      if (res.status === 429 && !_retried429) {
        const ra = Number(res.headers.get('retry-after') ?? '2');
        const wait = Number.isFinite(ra) ? Math.min(ra, 420) : 2;
        console.log(`[authz-matrix] 429 on ${method} ${pathname} — waiting ${wait}s (rate limiter working as designed)`);
        await new Promise((r) => setTimeout(r, wait * 1000));
        return this.req(pathname, { method, body, headers, _retried429: true });
      }
      const setCookie = res.headers.getSetCookie?.() ?? [];
      for (const c of setCookie) {
        const [pair] = c.split(';');
        const [name, value] = pair.split('=');
        if (value === '' || /expires=Thu, 01 Jan 1970/i.test(c)) {
          if (cookie?.startsWith(`${name}=`)) cookie = null;
        } else {
          cookie = `${name}=${value}`;
        }
      }
      let json = null;
      try {
        json = await res.json();
      } catch {
        /* body may be html/csv */
      }
      return { status: res.status, json };
    },
  };
}

// ── route inventory (generated) ──────────────────────────────────────────────

function walkRoutes(dir) {
  const out = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, entry.name);
    if (entry.isDirectory()) out.push(...walkRoutes(p));
    else if (entry.name === 'route.ts') out.push(p);
  }
  return out;
}

function apiPath(routeFile) {
  const rel = path.relative(path.join(ROOT, 'src', 'app', 'api'), routeFile);
  const segments = rel.split(path.sep).slice(0, -1); // drop route.ts
  return '/api' + (segments.length ? '/' + segments.join('/') : '');
}

function methodsOf(routeFile) {
  const src = fs.readFileSync(routeFile, 'utf8');
  return ['GET', 'POST', 'PATCH', 'PUT', 'DELETE'].filter((m) =>
    new RegExp(`export\\s+async\\s+function\\s+${m}\\b`).test(src),
  );
}

const ANON_ALLOW = [
  (m, p) => p.startsWith('/api/health/'),
  (m, p) => p === '/api/auth/login',
  (m, p) => p === '/api/auth/setup',
  (m, p) => p === '/api/auth/session' && m === 'GET', // session-state probe: 200 {authenticated:false}
  (m, p) => p.startsWith('/api/integrations/'),
];
const isAnonAllowed = (m, p) => ANON_ALLOW.some((fn) => fn(m, p));

// Routes where the tenant scope is server-enforced via ?tenant= (or body).
const TENANT_SCOPED_GET = [
  '/api/dashboard',
  '/api/analytics',
  '/api/export/analytics',
  '/api/export/incidents',
  '/api/export/services',
];
const ADMIN_READ = ['/api/users', '/api/audit'];

// ── helpers ──────────────────────────────────────────────────────────────────

let pass = 0;
const failures = [];
function expect(name, cond, extra = '') {
  if (cond) {
    pass++;
  } else {
    failures.push(`${name}${extra ? ` — ${extra}` : ''}`);
    console.error(`  ✗ ${name}${extra ? ` — ${extra}` : ''}`);
  }
}

const PLACEHOLDER_ID = 'matrix-placeholder-id';

async function ensureUser(client, { email, password, role, tenantId }) {
  const created = await client.req('/api/users', {
    method: 'POST',
    body: {
      name: `Matrix ${role}`,
      email,
      password,
      role,
      memberships: tenantId ? [{ tenantId, role: 'engineer' }] : [],
    },
  });
  if (created.status === 409) {
    // Exists from a previous run: rotate the password so this run's creds work.
    const users = await client.req('/api/users');
    const row = (users.json ?? []).find((u) => u.email === email);
    if (row) {
      await client.req(`/api/users/${row.id}`, { method: 'PATCH', body: { password, role } });
      return row.id;
    }
  }
  if (created.status !== 201) {
    throw new Error(`ensureUser(${email}) → ${created.status}: ${JSON.stringify(created.json)}`);
  }
  return created.json.id;
}

async function loginAs(email, password) {
  const client = makeClient();
  const res = await client.req('/api/auth/login', { method: 'POST', body: { email, password } });
  if (res.status !== 200) {
    throw new Error(`login(${email}) → ${res.status}: ${JSON.stringify(res.json)}`);
  }
  return client;
}

// ── main ─────────────────────────────────────────────────────────────────────

const routes = walkRoutes(path.join(ROOT, 'src', 'app', 'api')).map((f) => ({
  file: f,
  path: apiPath(f),
  methods: methodsOf(f),
}));
const inventory = routes.flatMap((r) => r.methods.map((m) => ({ method: m, path: r.path })));
console.log(`[authz-matrix] server ${BASE_URL} — ${inventory.length} route/method pairs generated`);

const owner = await loginAs(OWNER_EMAIL, OWNER_PASSWORD);
console.log('[authz-matrix] owner session ok');

// Tenants: need two (A = member, B = foreign).
const tenantsRes = await owner.req('/api/tenants');
const tenants = tenantsRes.json ?? [];
if (!Array.isArray(tenants) || tenants.length === 0) throw new Error('no tenants exist to scope against');
const tenantA = tenants[0];
let tenantB = tenants[1];
if (!tenantB) {
  const made = await owner.req('/api/tenants', {
    method: 'POST',
    body: { key: `matrix-b-${Date.now() % 100000}`, name: 'Matrix Tenant B' },
  });
  if (made.status !== 201) throw new Error(`could not create tenant B: ${JSON.stringify(made.json)}`);
  tenantB = made.json;
}
console.log(`[authz-matrix] tenant A=${tenantA.id} B=${tenantB.id}`);

// Role users (member of tenant A only).
const PW = 'Matrix-Run-PW!2026x';
const uniqueTag = `${Date.now() % 1000000}`;
const users = {
  viewer: { email: 'matrix-viewer@sentinel.test', role: 'viewer', tenantId: tenantA.id },
  eng: { email: 'matrix-eng@sentinel.test', role: 'engineer', tenantId: tenantA.id },
  exec: { email: 'matrix-exec@sentinel.test', role: 'executive', tenantId: tenantA.id },
};
for (const u of Object.values(users)) await ensureUser(owner, { ...u, password: PW });
const viewer = await loginAs(users.viewer.email, PW);
const eng = await loginAs(users.eng.email, PW);
const exec = await loginAs(users.exec.email, PW);
console.log('[authz-matrix] role users ready (viewer/engineer/executive, members of tenant A)');

// ── 1. anonymous → 401 on every protected route/method ──────────────────────
console.log('[authz-matrix] 1. anonymous matrix');
const anon = makeClient();
for (const { method, path } of inventory) {
  if (isAnonAllowed(method, path)) continue;
  const res = await anon.req(path.replace(/\[id\]/g, PLACEHOLDER_ID), { method });
  expect(
    `anon ${method} ${path} → 401`,
    res.status === 401,
    `got ${res.status}`,
  );
}

// ── 2. viewer: reads open, mutations closed, admin reads closed ─────────────
console.log('[authz-matrix] 2. viewer matrix');
for (const { method, path } of inventory) {
  if (isAnonAllowed(method, path)) continue;
  const target = path.replace(/\[id\]/g, PLACEHOLDER_ID);
  if (method === 'GET') {
    const res = await viewer.req(target);
    if (ADMIN_READ.includes(path)) {
      expect(`viewer GET ${path} → 403 (admin read)`, res.status === 403, `got ${res.status}`);
    } else {
      expect(
        `viewer GET ${path} → not 401/403`,
        res.status !== 401 && res.status !== 403,
        `got ${res.status}`,
      );
    }
  } else if (!path.startsWith('/api/auth/')) {
    const res = await viewer.req(target, { method, body: method === 'GET' ? undefined : {} });
    expect(`viewer ${method} ${path} → 403 (mutation)`, res.status === 403, `got ${res.status}`);
  }
}

// ── 3. cross-tenant enforcement (scoped user vs tenant B) ───────────────────
console.log('[authz-matrix] 3. cross-tenant matrix');
for (const route of TENANT_SCOPED_GET) {
  const denied = await eng.req(`${route}?tenant=${tenantB.id}`);
  expect(`engineer(A) GET ${route}?tenant=B → 403`, denied.status === 403, `got ${denied.status}`);
  const allowed = await eng.req(`${route}?tenant=${tenantA.id}`);
  expect(
    `engineer(A) GET ${route}?tenant=A → not 403`,
    allowed.status !== 403,
    `got ${allowed.status}`,
  );
  const deniedExec = await exec.req(`${route}?tenant=${tenantB.id}`);
  expect(`executive(A) GET ${route}?tenant=B → 403`, deniedExec.status === 403, `got ${deniedExec.status}`);
}

// Cross-tenant mutations.
const reportB = await exec.req('/api/reports', {
  method: 'POST',
  body: { periodHours: 1, tenantId: tenantB.id },
});
expect('executive(A) POST /api/reports {tenant:B} → 403', reportB.status === 403, `got ${reportB.status}`);
const reportA = await exec.req('/api/reports', {
  method: 'POST',
  body: { periodHours: 1, tenantId: tenantA.id },
});
expect(
  'executive(A) POST /api/reports {tenant:A} → 201',
  reportA.status === 201,
  `got ${reportA.status}: ${JSON.stringify(reportA.json)}`,
);
const serviceB = await eng.req('/api/services', {
  method: 'POST',
  body: { key: `matrix-svc-b-${uniqueTag}`, name: 'Matrix B', tenantId: tenantB.id },
});
expect('engineer(A) POST /api/services {tenant:B} → 403', serviceB.status === 403, `got ${serviceB.status}`);
void serviceB;

// Scoped user cannot widen to fleet-wide analytics by omitting ?tenant when
// they hold exactly one membership → auto-narrowed (no 403, no fleet leak).
const fleetView = await eng.req('/api/analytics');
expect(
  'engineer(A) GET /api/analytics (no tenant) → auto-narrowed, not 403',
  fleetView.status === 200,
  `got ${fleetView.status}`,
);

// ── 4. role floors on the new admin surfaces ────────────────────────────────
console.log('[authz-matrix] 4. admin surface matrix');
for (const route of ADMIN_READ) {
  expect(`viewer GET ${route} → 403`, (await viewer.req(route)).status === 403);
  expect(`engineer GET ${route} → 403`, (await eng.req(route)).status === 403);
  expect(`admin/owner GET ${route} → 200`, (await owner.req(route)).status === 200);
}

// ── summary ──────────────────────────────────────────────────────────────────
console.log(`\n[authz-matrix] ${pass} checks passed, ${failures.length} failed`);
if (failures.length > 0) {
  console.error('\nFAILURES:');
  for (const f of failures) console.error(`  - ${f}`);
  process.exit(1);
}
console.log('[authz-matrix] GATE EVIDENCE: 401/403/tenant-scope matrix PASS');
